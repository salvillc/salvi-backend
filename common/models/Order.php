			}
			
			if ($coordination)
			{
				if ((($coordination->additional_type == Coordination::ADD_TYPE_WITHOUT_BUDGET && !$this->non_budget_order) ||
					($coordination->additional_type == Coordination::ADD_TYPE_WITHOUT_BUDGET && $this->non_budget_order && $this->budget)))
