		{
			throw new NotEnoughBudgetException('Сума замовлення перевищує залишок суми вибраного бюджету');
		}
		if ($this->budget && $this->budget->status != Budget::STATUS_ACTIVE)
		{
			throw new BudgetNotAvailableException('Термін дії бюджету закінчився, виберіть будь ласка інший');
		}
		$totalProducts = OrderProduct::find()->where(['order_id' => $this->id])->count();
		if ($totalProducts == 0)
		{
			throw new MissingProductException('Добавте хоча б один товар до замовлення');
		}
		$this->calculateAvailableSpecificationProduct(true);

