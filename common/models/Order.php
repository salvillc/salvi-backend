	/**
	 * @param bool $is_minus
	 *
	 * @throws NotEnoughQuantityProductException
	 * @throws Exception
	 */
	public function calculateAvailableSpecificationProduct($is_minus = true)
	{
		$errors = [];
		$transaction = Yii::$app->db->beginTransaction();
		$specification = Specification::find()->joinWith('locations')->where(['company_id' => $this->company_id])
			->andWhere(['specification_location.location_id' => $this->location_id])->all();
		$query = OrderProduct::find()->joinWith([
			'product',
			'specificationsProduct' => function ($query) use ($specification)
			{
				if ($specification)
				{
					$query->onCondition([
						'in',
						'specification_product.specification_id',
						ArrayHelper::getColumn($specification, 'id'),
					]);
				}
			},
		]);
		$query->where(['order_product.order_id' => $this->id]);
		$products = $query->all();
		if ($products)
		{
			foreach ($products as $product)
			{
				if ($product->specificationsProduct)
				{
					$status = ArrayHelper::getColumn($product->specificationsProduct, 'status');
					$key = array_search(1, $status);
					if (false !== $key)
					{
						if ($product->specificationsProduct[$key]->quantity != '-1')
						{
							$object = $product->specificationsProduct[$key];
							\Yii::info($object);
							if ($is_minus)
							{
								$newQuantity = $object->quantity - $product->quantity;
							}
							else
							{
								$newQuantity = $object->quantity + $product->spec_quantity;
							}
							if ($newQuantity >= 0)
							{
								$object->quantity = $newQuantity;
								$product->spec_quantity = $product->quantity;
							}
							else
							{
								if ($product->approved != OrderProduct::NOT_APPROVED)
								{
									$product->spec_quantity = $object->quantity;
								}
								else
								{
									$errors[] = $product->product->name . ' доступно - ' . $object->quantity;
								}
								$object->quantity = 0;
							}
							$product->save();
							$object->save();
						}
					}
				}
			}
		}
		if ($is_minus && !empty($errors))
		{
			$transaction->rollBack();
			$message = 'Деякі вибрані товари не доступні у вказаній кількість';
			throw new NotEnoughQuantityProductException($message);
		}
		else
		{
			$transaction->commit();
		}
	}
	
	/**
	 * @return bool
	 */
	public function changeStatusOnAtSupplier()
	{
		$this->status = self::STATUS_AT_SUPPLIER;
		$result = $this->save();
		if ($result)
		{
			self::budgetReserve($this);
			NotificationHelper::atSupplierOrder($this);
			NotificationHelper::atSupplierOrderOwner($this);
		}
		
		return $result;
	}
	
	public static function budgetReserve(Order $order)
	{
		if ((!is_null($order->budget_id) && $order->budget_id > 0) && $order->total_sum != $order->budget_reserve_sum)
		{
			$order->is_budget_reserve = 1;
			
			$budget = Budget::find()->where(['id' => $order->budget_id])->one();
			
			$budget->sum = round($budget->sum + $order->budget_reserve_sum - $order->total_sum, 2);
			
			$budget->save();
			
			$order->budget_reserve_sum = $order->total_sum;
			
			$order->save();
		}
	}
	
	public static function budgetUnReserve(Order $order)
	{
		if (!is_null($order->budget_id) && $order->budget_id > 0 && $order->is_budget_reserve == 1)
		{
			$order->is_budget_reserve = 0;
			
			$budget = Budget::find()->where(['id' => $order->budget_id])->one();
			
			$budget->sum = round($budget->sum + $order->total_sum, 2);
			
			$order->budget_reserve_sum = 0;
			
			$budget->save();
			
			$order->save();
		}
	}
	
	public function changeStatusOnAtManager()
	{
		$this->status = self::STATUS_AT_MANAGER;
		$this->start_time = date('U');
		$result = $this->save();
		$products = OrderProduct::find()->where(['order_product.order_id' => $this->id])
			->andWhere('quantity != on_approve_quantity')->all();
		if ($products)
		{
			NotificationHelper::atManagerOrderChanged($this, $products);
		}
		if ($result)
		{
			self::budgetReserve($this);
			NotificationHelper::atManagerOrder($this);
			NotificationHelper::atManagerOrderOwner($this);
			NotificationHelper::atManagerOrderManager($this);
			
			
			// send email`s
			$this->sendEmals($this);
		}
		
		return $result;
	}
	
	
