			{
				$percent = 0;
				if ($this->budget->sum > 0)
				{
					$percent = ($this->budget->availableSum - $this->total_sum) / $this->budget->sum;
				}
				//Yii::error($percent);
				//Yii::error($this->budget->availableSum);
				$availableSum = $this->budget->availableSum - $this->total_sum;
				if ($percent <= 0.2)
				{
					NotificationHelper::soonEndBudget($this->budget);
					NotificationHelper::soonEndBudgetOwner($this->budget);
				}
			}
			if ($availableBudget < $this->total_sum)
			{
				NotificationHelper::orderMoreThanBudgetManager($this);
			}
			$coordination = OrderCoordination::find()->where(['order_id' => $this->id])->andWhere(['status' => 0])
				->orderBy('order ASC')->one();
			$productStart = OrderProduct::find()->where(['order_id' => $this->id])->all();
			if ($productStart)
			{
				foreach ($productStart as $product)
				{
					$product->start_quantity = $product->quantity;
					$product->on_approve_quantity = $product->quantity;
					$product->save();
				}
			}
			$product = OrderProduct::find()->where(['order_id' => $this->id])->andWhere(['catalog' => 1])->all();
			$usersIsset = false;
			$activeUsers = [];
			//Yii::error($coordination);
			if ($coordination)
			{
				if ($coordination->all_roles)
				{
					$users = AuthAssignment::find()->where([
							'in',
							'item_name',
							ArrayHelper::getColumn($coordination->roles, 'role'),
						])->all();
					//Yii::error($users);
					if ($users)
					{
						$activeUsers = User::find()->leftJoin('user_location ul', 'user.id = ul.user_id')
							->where(['user.status' => User::STATUS_ACTIVE])->andWhere([
								'in',
								'user.id',
								ArrayHelper::getColumn($users, 'user_id'),
							])->andWhere(['user.company_id' => $coordination->company_id])
							->andWhere(['ul.location_id' => $this->location_id])->all();
						//Yii::error($activeUsers);
						if ($activeUsers)
