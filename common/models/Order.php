	/**
	 * @return bool
	 * @throws Throwable
	 */
	public function changeStatusToStart()
	{
		$oldStatus = $this->status;
		$this->status = self::STATUS_OPEN;
		$result = $this->save();
		if ($result)
		{
			$this->calculateAvailableSpecificationProduct(false);
			$currentStep = OrderCoordination::find()->where(['order_id' => $this->id])->andWhere(['next_step' => 1])
				->one();
			OrderCoordination::updateAll(['status' => 0, 'next_step' => 0], ['order_id' => $this->id]);
			$coordination = OrderCoordination::find()->where(['order_id' => $this->id])->one();
			if ($coordination != false)
			{
				$coordination->next_step = 1;
				$coordination->save();
			}
			/** @var  $user User */
			$user = Yii::$app->user->getIdentity();
			if ($user->manager)
			{
				NotificationHelper::declineByManagerOrder($this, $user);
				NotificationHelper::declineByManagerOrderOwner($this, $user);
			}
			elseif ($oldStatus == self::STATUS_ON_APPROVE)
			{
				if ($currentStep)
				{
					NotificationHelper::declineByUserOrder($this, $user, $currentStep);
					NotificationHelper::declineByUserOrderOwner($this, $user, $currentStep);
				}
			}
		}
		
		return $result;
	}
	
