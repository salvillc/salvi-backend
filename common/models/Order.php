	/**
	 * @return bool
	 * @throws NotEnoughAllQuantityProductException
	 * @throws NotEnoughQuantityProductException
	 */
	public function checkAvailableSpecificationProduct()
	{
		$errors = [];
		$specification = Specification::find()->joinWith('locations')->where(['company_id' => $this->company_id])
			->andWhere(['specification_location.location_id' => $this->location_id])->all();
		$query = OrderProduct::find()->joinWith([
			'product',
			'specificationsProduct' => function ($query) use ($specification)
			{
				if ($specification)
				{
					$query->onCondition([
						'in',
						'specification_product.specification_id',
						ArrayHelper::getColumn($specification, 'id'),
					]);
				}
			},
		]);
		$query->where(['order_product.order_id' => $this->id]);
		$query->andWhere(['order_product.approved' => OrderProduct::NOT_APPROVED]);
		$products = $query->all();
		$totalProduct = OrderProduct::find()->where(['order_product.order_id' => $this->id])->count();
		if ($products)
		{
			foreach ($products as $product)
			{
				$key = false;
				if ($product->specificationsProduct)
				{
					$status = ArrayHelper::getColumn($product->specificationsProduct, 'status');
					$key = array_search(1, $status);
				}
				if ($product->specificationsProduct && $key !== false && $product->specificationsProduct[$key]->quantity != '-1')
				{
					$object = $product->specificationsProduct[$key];
					$newQuantity = $object->quantity - $product->quantity;
					if ($newQuantity >= 0)
					{
						$object->quantity = $newQuantity;
					}
					else
					{
						$errors[] = $product->product->name . ' доступно - ' . $object->quantity;
						//$product->specificationsProduct[$key]->quantity = 0;
					}
				}
				else
				{
					if ($product->view_only)
					{
						$errors[] = $product->product->name . ' недоступно для локації';
					}
				}
			}
		}
		if (!empty($errors) && count($errors) == $totalProduct)
		{
			$message = 'Всі вибрані товари не доступні у вказаній кількість';
			throw new NotEnoughAllQuantityProductException($message);
		}
		if (!empty($errors))
		{
			$message = 'Деякі вибрані товари не доступні у вказаній кількість';
			throw new NotEnoughQuantityProductException($message);
		}
		else
		{
			return 1;
		}
	}
	
	/**
	 * @throws Exception
	 * @throws Throwable
	 * @throws StaleObjectException
	 */
	public function splitOrder()
	{
		$transaction = Yii::$app->db->beginTransaction();
		
		$newOrder = $this->copyOrder();
		if ($newOrder)
		{
			NotificationHelper::orderNeedModerationManager($newOrder);
		}
		$specification = Specification::find()->joinWith('locations')->where(['company_id' => $this->company_id])
			->andWhere(['specification_location.location_id' => $this->location_id])->all();
		$query = OrderProduct::find()->joinWith([
			'product',
			'specificationsProduct' => function ($query) use ($specification)
			{
				if ($specification)
				{
					$query->onCondition([
						'in',
						'specification_product.specification_id',
						ArrayHelper::getColumn($specification, 'id'),
					]);
				}
			},
		]);
		$query->where(['order_product.order_id' => $this->id]);
		$query->andWhere(['order_product.approved' => OrderProduct::NOT_APPROVED]);
		$products = $query->all();
		if ($products)
		{
			foreach ($products as $product)
			{
				$key = false;
				if ($product->specificationsProduct)
				{
					$status = ArrayHelper::getColumn($product->specificationsProduct, 'status');
					$key = array_search(1, $status);
				}
				if ($product->specificationsProduct && false !== $key && $product->specificationsProduct[$key]->quantity != '-1')
				{
					$newQuantity = $product->specificationsProduct[$key]->quantity - $product->quantity;
					if ($newQuantity < 0)
					{
						$product->quantity -= abs($newQuantity);
						$product->total_sum = NumberHelper::calculateTaxPrice($product);
						$product->view_only = 0;
						$product->save();
						$newProduct = new OrderProduct();
						$newProduct->setAttributes($product->attributes);
						$newProduct->order_id = $newOrder->id;
						$newProduct->quantity = abs($newQuantity);
						$newProduct->total_sum = NumberHelper::calculateTaxPrice($newProduct);
						$newProduct->save();
						if ($product->quantity == 0)
						{
							$product->delete();
						}
					}
				}
				else
				{
					if ($product->view_only)
					{
						$newProduct = new OrderProduct();
						$newProduct->setAttributes($product->attributes);
						$newProduct->order_id = $newOrder->id;
						$newProduct->save();
						$product->delete();
					}
				}
			}
			$this->total_sum = OrderHelper::getTotalSum($this->id);
			$this->save();
			$newOrder->status = Order::STATUS_MODERATION;
			$newOrder->total_sum = OrderHelper::getTotalSum($newOrder->id);
			$newOrder->setStatusModeration();
			$newOrder->save();
			$transaction->commit();
			
			return $newOrder->id;
		}
		else
		{
			$transaction->rollBack();
		}
		
		return false;
	}
	
	/**
	 * @return bool|Order
	 */
	public function copyOrder()
	{
		$tomorrow = strtotime("+1 day");
		$newOrder = new self();
		$newOrder->setAttributes($this->attributes);
		if ($this->delivery_date <= $tomorrow)
		{
			$newOrder->delivery_date = $tomorrow;
		}
		$newOrder->status = Order::STATUS_OPEN;
		if ($newOrder->save())
		{
			$this->copyCoordination($newOrder);
			$this->copyUserCoordination($newOrder);
			
			return $newOrder;
		}
		
		return false;
	}
	
